const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const scope = {module:{exports:{}},console,Date,Map,Set};
vm.runInNewContext(fs.readFileSync('data/macros.gs','utf8'),scope);
const api=scope.module.exports;
const id=(n)=>'00000000-0000-4000-8000-'+String(n).padStart(12,'0');
const a={category_id:id(1),type:'Расход',name:'Продукты',active:true,deactivated_period:''};
const b={category_id:id(2),type:'Расход',name:'Кафе',active:true,deactivated_period:''};
const child={subcategory_id:id(3),current_category_id:a.category_id,name:'Доставка',active:true};
const registry={categories:[a,b],children:[child],history:[]};
const visible=['11.11.2026','Продукты','Доставка',100,'Расход',''];
const plain=x=>JSON.parse(JSON.stringify(x));
const first=api.fbReconcile([api.FB.header,visible],registry,[],()=>id(4));
assert.equal(first.service[0][3],'valid');
assert.equal(first.service[0][0],a.category_id);
const old=Object.fromEntries(api.FB.snapshotHeader.map((k,i)=>[k,first.saved[0][i]]));
const moved={categories:[{...a,active:false,deactivated_period:'2026-11'},b],children:[{...child,current_category_id:b.category_id}],history:[{category_id:a.category_id,subcategory_id:child.subcategory_id}]};
const row=[...visible,...first.service[0]];
row[3]=200;
const unchanged=api.fbReconcile([api.FB.header,row],moved,[old],()=>id(5));
assert.equal(unchanged.service[0][0],a.category_id);
assert.equal(unchanged.service[0][3],'valid');
row[1]='Кафе';
const changed=api.fbReconcile([api.FB.header,row],moved,[old],()=>id(5));
assert.equal(changed.service[0][0],b.category_id);
const duplicate=api.fbReconcile([api.FB.header,row,row],moved,[old],()=>id(5));
assert.equal(duplicate.service[0][3],'duplicate_or_invalid_transaction_id');
const invalid=[...visible];invalid[0]='31.11.2026';
assert.equal(api.fbReconcile([api.FB.header,invalid],registry,[],()=>id(4)).service[0][3],'invalid_date');
assert.equal(api.fbDate('01.11.2026'),46327);
assert.equal(api.fbDate('2026-11-01'),46327);
assert.throws(()=>api.fbDate(true));
assert.throws(()=>api.fbAmount('0x10'));
assert.throws(()=>api.fbAmount(0));
const restored=[...visible,...first.service[0]];
const totals=api.fbArchiveValues([api.FB.header,restored],registry,{year:2026,month:11,key:'2026-11'});
assert.equal(totals.expenses,100);
assert.equal(totals.totals[a.category_id],100);
assert.equal(totals.totals[b.category_id],0);
assert.throws(()=>api.fbArchiveValues([api.FB.header,restored],registry,{year:2026,month:12,key:'2026-12'}));
assert.throws(()=>api.fbArchiveValues([api.FB.header,restored],{...registry,categories:[{...a,active:false,deactivated_period:'2026-10'},b]},{year:2026,month:11,key:'2026-11'}));
console.log('Apps Script core: reconciliation, move, deactivation, duplicate IDs, period checks passed');
